/*
 * Состав бокса — единый контент-источник для главной и 7 страниц товара
 * (PATCH-1 §2, FIX-05/36/49/52/53/70; spec product-page «Состав бокса — единый
 * источник с главной»). Дословно из прототипов landing.html и collectio-*.html.
 *
 * Физический бокс одинаков для всех SKU: варьируется только позиция 01 —
 * на главной «твоё растение» и ссылка на /lab, на карточке растение,
 * число компонентов и якорь рецептуры /lab#rec-{slug}.
 */

export type BoxItem = {
  n: string;
  text: string;
  /* мост в лабораторию грунта — только у позиции 01 */
  link?: { label: string; href: string };
  /* раскрытые подпункты «Забота о корнях и твоих руках» (4 штуки, FIX-36/49/70) */
  sub?: string[];
};

const labLinkLabel = "подробнее в лаборатории грунта →";

const rest: BoxItem[] = [
  { n: "02", text: "Керамзитовый дренаж, 10–20 мм" },
  {
    n: "03",
    text: "«Забота о корнях и твоих руках»",
    sub: [
      "перчатки, чтобы не жалеть рук",
      "2 палочки для корней, чтобы бережно разобрать ком: мягкое дерево не режет корни",
      "баночка угольной пудры, чтобы подсушить свежий срез",
      "корневин, чтобы на свежем срезе заложились новые корни",
    ],
  },
  { n: "04", text: "Дневник растения на год" },
  { n: "05", text: "Листовка с гайдом по пересадке" },
];

/* Опись бокса: позиция 01 задаётся вызывающей стороной, 02–05 — постоянные. */
export function boxContents(soil: { text: string; href: string }): BoxItem[] {
  return [
    { n: "01", text: soil.text, link: { label: labLinkLabel, href: soil.href } },
    ...rest,
  ];
}
